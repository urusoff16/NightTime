export type UiTextKey = keyof (typeof messages)['en'];

export function languageFromLocale(locale: string | undefined): UiLanguage {
  return locale?.toLowerCase().startsWith('ru') ? 'ru' : 'en';
}

export function resolveUiLanguage(language: ExtensionSettings['language']): UiLanguage {
  if (language === 'ru' || language === 'en') return language;
  const chromeLocale = typeof chrome !== 'undefined' ? chrome.i18n?.getUILanguage?.() : undefined;
  return languageFromLocale(
    chromeLocale ?? (typeof navigator === 'undefined' ? undefined : navigator.language),
  );
}

export function t(
  key: UiTextKey,
  language: UiLanguage,
  values: Record<string, string | number> = {},
): string {
  return Object.entries(values).reduce<string>(
    (text, [name, value]) => text.replaceAll(`{${name}}`, String(value)),
    String(messages[language][key]),
  );
}
